// Scans public/characters and (re)writes src/game/characters.generated.ts.
//
// A person character is one identity (`girl-3`) rendered in several art states. Files are named
// `<id>-<state>.webp` — e.g. `girl-3-base.webp`, `girl-3-heart.webp`. `girl-*` = female, `man-*` = male.
// Every character MUST provide every state in REQUIRED_STATES (no fallback); a missing file fails the
// build with a clear message. Drop a new identity's files in and the next dev/build picks it up — no
// code edit. (Monsters stay in config.ts, since each carries gameplay stats.) Output is committed so
// tsc/editors work without running this first.
import { readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Art states every person character must ship. Add one here + author the files to extend. */
const REQUIRED_STATES = ['base', 'heart']
const GENDER_BY_PREFIX = { girl: 'f', man: 'm' }

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const charactersDir = join(root, 'public', 'characters')
const outFile = join(root, 'src', 'game', 'characters.generated.ts')

// id → { gender, states: Set<state> }, gathered from `<prefix>-<n>-<state>.webp`.
const chars = new Map()
const personFile = /^((girl|man)-[^-]+)-([^-]+)\.webp$/

for (const file of readdirSync(charactersDir)) {
  if (!file.endsWith('.webp') || file.startsWith('monster-')) continue
  const m = personFile.exec(file)
  if (!m) throw new Error(`Character file '${file}' must be named '<girl|man>-<n>-<state>.webp'`)
  const [, id, prefix, state] = m
  if (!REQUIRED_STATES.includes(state)) {
    throw new Error(`Unknown art state '${state}' in '${file}' (expected: ${REQUIRED_STATES.join(', ')})`)
  }
  const entry = chars.get(id) ?? { gender: GENDER_BY_PREFIX[prefix], states: new Set() }
  entry.states.add(state)
  chars.set(id, entry)
}

const ids = [...chars.keys()].sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
if (ids.length === 0) throw new Error(`No person portraits found in ${charactersDir}`)

for (const id of ids) {
  const missing = REQUIRED_STATES.filter((s) => !chars.get(id).states.has(s))
  if (missing.length > 0) throw new Error(`Character '${id}' is missing states: ${missing.join(', ')}`)
}

const roster = { f: [], m: [] }
for (const id of ids) roster[chars.get(id).gender].push(id)

const artLines = ids
  .map((id) => `  '${id}': { ${REQUIRED_STATES.map((s) => `${s}: '${id}-${s}'`).join(', ')} },`)
  .join('\n')

const out = `// AUTO-GENERATED by scripts/gen-characters.mjs — do not edit. Run \`bun run gen:characters\`.
import type { Gender } from './types'

/** Art states every person character ships (see scripts/gen-characters.mjs REQUIRED_STATES). */
export type ArtState = ${REQUIRED_STATES.map((s) => `'${s}'`).join(' | ')}

/** Character identities per gender (art is keyed separately by state, below). */
export const PERSON_ROSTER: Record<Gender, readonly string[]> = {
  f: [${roster.f.map((id) => `'${id}'`).join(', ')}],
  m: [${roster.m.map((id) => `'${id}'`).join(', ')}],
}

/** Sprite key per (character, state) → public/characters/<key>.webp. */
export const PERSON_ART: Record<string, Record<ArtState, string>> = {
${artLines}
}
`

writeFileSync(outFile, out)
console.log(
  `characters.generated.ts: ${roster.f.length} girl + ${roster.m.length} man × [${REQUIRED_STATES.join(', ')}]`,
)
